import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { AssistCapReachedError, fakeAssistClient } from '@compadr/assist'
import { createFixtureRepo, type FixtureRepo } from '@compadr/engine/testing'
import { Client } from '@modelcontextprotocol/sdk/client/index.js'
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { createServer } from './server.ts'

let fixture: FixtureRepo
let client: Client

beforeAll(async () => {
  fixture = createFixtureRepo([
    {
      date: '2026-01-10T09:00:00Z',
      files: {
        'docs/adr/0001-pool.md': [
          '# 1. Pool the connections',
          '',
          'Status: Accepted',
          'Date: 2026-01-10',
          '',
          '## Context',
          '',
          'Each request opened a connection.',
          '',
          '## Decision',
          '',
          'The pool lives in `src/db/pool.ts:1`. One pool serves the process.',
          '',
          '## Consequences',
          '',
          'Fewer connections.',
          '',
        ].join('\n'),
        'docs/adr/0002-old-pool.md': [
          '# 2. Old pool',
          '',
          'Status: Superseded by ADR-0001',
          '',
        ].join('\n'),
        'src/db/pool.ts':
          'export function createPool() {}\n// ADR-0002: one pool.\n',
      },
    },
  ])
  const [clientSide, serverSide] = InMemoryTransport.createLinkedPair()
  await createServer({
    repository: fixture.path,
    ref: 'HEAD',
    generatorVersion: '0.0.0',
    today: () => '2026-11-03',
  }).connect(serverSide)
  client = new Client({ name: 'test', version: '0.0.0' })
  await client.connect(clientSide)
})

afterAll(async () => {
  await client.close()
  fixture.remove()
})

async function call(name: string, args: Record<string, unknown>) {
  const result = (await client.callTool({ name, arguments: args })) as {
    content: { type: string; text: string }[]
    isError?: boolean
  }
  const text = result.content[0]!.text
  return result.isError ? { error: text } : (JSON.parse(text) as unknown)
}

describe('compadr MCP server', () => {
  it('lists seven read-only tools', async () => {
    const { tools } = await client.listTools()
    expect(tools.map(tool => tool.name)).toEqual([
      'memory',
      'decisions_for_file',
      'decisions_for_symbol',
      'check_change_against_decisions',
      'get_decision',
      'search_decisions',
      'propose_decision',
    ])
    expect(tools.every(tool => tool.annotations?.readOnlyHint)).toBe(true)
  })

  it('says when no record cites a symbol', async () => {
    expect(
      await call('decisions_for_symbol', { symbol: 'createPool' })
    ).toEqual({
      error:
        'No decision record cites createPool. Use decisions_for_file on the file that declares it.',
    })
  })

  it('gives the memory card as Markdown', async () => {
    const result = (await client.callTool({
      name: 'memory',
      arguments: {},
    })) as {
      content: { text: string }[]
    }
    const text = result.content[0]!.text
    expect(text.startsWith('<!-- Generated by Compadr: compadr map -->')).toBe(
      true
    )
    expect(text).toContain('- 0001 Pool the connections')
  })

  it('gives the decisions of a file in one call', async () => {
    // The record cites lines of the file (2), the file cites the record that
    // 0001 replaces (2), both ways at once (2).
    expect(
      await call('decisions_for_file', { path: './src/db/pool.ts' })
    ).toEqual({
      repository: expect.any(String) as string,
      ref: 'HEAD',
      commit: expect.any(String) as string,
      path: 'src/db/pool.ts',
      inForce: [
        {
          decision: 1,
          title: 'Pool the connections',
          rule: 'The pool lives in `src/db/pool.ts:1`.',
          weight: 6,
          read: 'lines',
          replaces: [2],
        },
      ],
      context: [],
      outOfForce: [],
    })
    expect(
      await call('decisions_for_file', {
        path: 'src/db/pool.ts',
        detail: 'full',
      })
    ).toMatchObject({
      inForce: [
        {
          decision: 1,
          scope: 'file',
          replaces: [2],
          links: [
            { source: 'record-cites-path', lines: { start: 1, end: 1 } },
            { source: 'file-cites-record', line: 2 },
          ],
        },
      ],
    })
    expect(
      await call('decisions_for_file', {
        path: join(fixture.path, 'src/db/pool.ts'),
      })
    ).toMatchObject({ path: 'src/db/pool.ts' })
    expect(await call('decisions_for_file', { path: '/etc/hosts' })).toEqual({
      error: '/etc/hosts is outside the repository.',
    })
  })

  it('checks a change against the decisions', async () => {
    const diff = [
      'diff --git a/src/db/pool.ts b/src/db/pool.ts',
      '--- a/src/db/pool.ts',
      '+++ b/src/db/pool.ts',
      '@@ -1 +1,2 @@',
      '-export function createPool() {}',
      '+export function createPool(size: number) {}',
      '+// ADR-0002: still one pool.',
    ].join('\n')
    expect(
      await call('check_change_against_decisions', { diff })
    ).toMatchObject({
      ref: 'HEAD',
      files: [{ path: 'src/db/pool.ts', status: 'modified' }],
      signals: [
        { type: 'superseded-decision-cited', decision: 2, supersededBy: [1] },
        { type: 'cited-lines-changed', decision: 1 },
      ],
      inForce: [{ decision: 1, scope: 'file', files: ['src/db/pool.ts'] }],
    })
    expect(
      await call('check_change_against_decisions', { diff: 'No change.' })
    ).toEqual({
      error:
        'The diff names no file. Pass the output of git diff, in the unified format.',
    })
  })

  it('describes a decision and searches the records', async () => {
    expect(await call('get_decision', { number: 1 })).toMatchObject({
      title: 'Pool the connections',
      inForce: true,
      rule: {
        text: 'The pool lives in `src/db/pool.ts:1`.',
        source: 'first-sentence',
      },
      outline: [{ index: 1, heading: null }],
      decision: [{ index: 1, heading: null }],
      codeLinks: [{ cited: 'src/db/pool.ts', count: 1, lines: true }],
      citedSymbols: [],
      citedBy: { files: 0, citations: 0 },
    })
    // Picked subsections come without the links, unless asked for.
    expect(
      await call('get_decision', { number: 1, sections: [1] })
    ).toMatchObject({ decision: [{ index: 1 }], codeLinks: [] })
    expect(
      await call('get_decision', {
        number: 1,
        sections: 'none',
        codeLinks: 'full',
        citedBy: 'files',
      })
    ).toMatchObject({
      decision: [],
      codeLinks: [{ cited: 'src/db/pool.ts:1', recordLine: 12 }],
      citedBy: [],
    })
    expect(await call('get_decision', { number: 9 })).toEqual({
      error: 'The repository has no decision 9.',
    })
    expect(await call('search_decisions', { query: 'pool process' })).toEqual([
      expect.objectContaining({
        number: 1,
        excerpt: expect.stringContaining('One pool') as string,
      }),
    ])
    expect(
      await call('search_decisions', { query: 'pool', status: 'superseded' })
    ).toEqual([expect.objectContaining({ number: 2 })])
  })

  it('drafts a proposed decision like the latest record', async () => {
    const draft = (await call('propose_decision', {
      title: 'Pool size',
      decision: 'The pool holds ten connections.',
      parent: 1,
      rule: 'The pool holds ten connections,  set in code.',
    })) as { path: string; content: string; notes: string[] }
    expect(draft.path).toBe('docs/adr/0003-pool-size.md')
    expect(draft.content).toBe(
      [
        '---',
        'compadr:',
        // Both records cite src/db/pool.ts: they form a proposed feature.
        '  feature: pool',
        '  parent: 1',
        '  rule: The pool holds ten connections, set in code.',
        '---',
        '',
        '# 3. Pool size',
        '',
        'Status: Proposed',
        'Amends ADR 0001.',
        '',
        '## Context',
        '',
        '_To be written._',
        '',
        '## Decision',
        '',
        'The pool holds ten connections.',
        '',
        '## Consequences',
        '',
        '_To be written._',
        '',
      ].join('\n')
    )
    expect(draft.notes).toHaveLength(3)
    expect(draft.notes).toContain(
      'The repository does not declare the feature "pool" yet.'
    )
    const bare = (await call('propose_decision', { title: 'Pool size' })) as {
      notes: string[]
    }
    expect(bare.notes[0]).toMatch(/^The record declares no rule/)
  })

  it('computes the report again when the commit changes', async () => {
    writeFileSync(
      join(fixture.path, 'docs/adr/0003-size.md'),
      '# 3. Size\n\nStatus: Accepted\n\nThe pool in `src/db/pool.ts` holds ten.\n'
    )
    fixture.git('add', '.')
    // The CI runner has no git identity: the commit names its own.
    fixture.git(
      '-c',
      'user.name=Compadr',
      '-c',
      'user.email=fixture@example.com',
      'commit',
      '--quiet',
      '-m',
      'size'
    )
    expect(
      await call('decisions_for_file', { path: 'src/db/pool.ts' })
    ).toMatchObject({
      inForce: [{ decision: 1 }, { decision: 3 }],
    })
  })
})

describe('the semantic option of check_change_against_decisions', () => {
  const diff = [
    'diff --git a/src/db/pool.ts b/src/db/pool.ts',
    '--- a/src/db/pool.ts',
    '+++ b/src/db/pool.ts',
    '@@ -1 +1,2 @@',
    ' export function createPool() {}',
    '+export const second = createPool()',
  ].join('\n')

  async function serve(optIn: boolean) {
    const repo = createFixtureRepo([
      {
        date: '2026-01-10T09:00:00Z',
        files: {
          'docs/adr/0001-pool.md': [
            '# 1. Pool the connections',
            '',
            'Status: Accepted',
            '',
            '## Decision',
            '',
            'The pool lives in `src/db/pool.ts:1`. One pool serves the process.',
            '',
          ].join('\n'),
          'src/db/pool.ts': 'export function createPool() {}\n',
          ...(optIn
            ? { 'docs/adr/compadr.yml': 'assist:\n  semantic: true\n' }
            : {}),
        },
      },
    ])
    let sent = 0
    const [clientSide, serverSide] = InMemoryTransport.createLinkedPair()
    await createServer({
      repository: repo.path,
      ref: 'HEAD',
      generatorVersion: '0.0.0',
      env: {
        COMPADR_ASSIST_URL: 'https://assist.test',
        COMPADR_ASSIST_TOKEN: 't',
      },
      assistClient: () => {
        const fake = fakeAssistClient({
          answer: () => ({
            findings: [
              {
                decision: 1,
                verdict: 'violated',
                quote: 'One pool serves the process.',
                evidence: {
                  path: 'src/db/pool.ts',
                  text: '+export const second = createPool()',
                },
                explanation: 'The change opens a second pool.',
              },
            ],
          }),
        })
        return {
          suggest: request => {
            sent++
            return fake.suggest(request)
          },
        }
      },
    }).connect(serverSide)
    const agent = new Client({ name: 'test', version: '0.0.0' })
    await agent.connect(clientSide)
    const answer = async (semantic?: boolean) => {
      const result = (await agent.callTool({
        name: 'check_change_against_decisions',
        arguments: semantic === undefined ? { diff } : { diff, semantic },
      })) as { content: { text: string }[] }
      return JSON.parse(result.content[0]!.text) as Record<string, unknown>
    }
    return {
      answer,
      sent: () => sent,
      close: async () => {
        await agent.close()
        repo.remove()
      },
    }
  }

  it('adds the findings that the guard keeps, with the quoted rule', async () => {
    const server = await serve(true)
    expect(await server.answer(true)).toMatchObject({
      semantic: {
        status: 'done',
        findings: [
          {
            decision: 1,
            title: 'Pool the connections',
            verdict: 'violated',
            quote: 'One pool serves the process.',
            line: 2,
          },
        ],
      },
    })
    expect(await server.answer()).not.toHaveProperty('semantic')
    expect(server.sent()).toBe(1)
    await server.close()
  })

  it('sends nothing when compadr.yml does not turn it on', async () => {
    const server = await serve(false)
    expect(await server.answer(true)).toMatchObject({
      semantic: { status: 'skipped' },
    })
    expect(server.sent()).toBe(0)
    await server.close()
  })
})

describe('the assist option of propose_decision', () => {
  const change = (path: string) =>
    [
      `diff --git a/${path} b/${path}`,
      `--- a/${path}`,
      `+++ b/${path}`,
      '@@ -1 +1,2 @@',
      ' export function createPool() {}',
      '+export const size = 20',
    ].join('\n')

  async function serve(options: {
    optIn: boolean
    notNeeded?: string
    capped?: boolean
  }) {
    const repo = createFixtureRepo([
      {
        date: '2026-01-10T09:00:00Z',
        files: {
          'docs/adr/0001-pool.md': [
            '# 1. Pool the connections',
            '',
            'Status: Accepted',
            '',
            '## Decision',
            '',
            'The pool lives in `src/db/pool.ts:1`. One pool serves the process.',
            '',
          ].join('\n'),
          'src/db/pool.ts': 'export function createPool() {}\n',
          'config/secrets/keys.ts': 'export const key = "k"\n',
          ...(options.optIn
            ? {
                'docs/adr/compadr.yml':
                  'assist:\n  semantic: true\n  exclude:\n    - config/secrets\n',
              }
            : {}),
        },
      },
    ])
    const sent: { diff: string }[] = []
    const [clientSide, serverSide] = InMemoryTransport.createLinkedPair()
    await createServer({
      repository: repo.path,
      ref: 'HEAD',
      generatorVersion: '0.0.0',
      today: () => '2026-11-19',
      env: {
        COMPADR_ASSIST_URL: 'https://assist.test',
        COMPADR_ASSIST_TOKEN: 't',
      },
      assistClient: () => {
        const fake = fakeAssistClient({
          answer: () => ({
            notNeeded: options.notNeeded ?? null,
            title: 'Pool size',
            rule: 'The pool keeps twenty connections at most.',
            amends: [1],
            supersedes: [],
            context: 'The load grew.',
            decision: [
              {
                heading: 'Twenty connections',
                text: '`src/db/pool.ts` keeps twenty connections.',
              },
            ],
            consequences: 'The database sees twenty connections per process.',
            codeRefs: ['`src/db/pool.ts`'],
          }),
        })
        return {
          suggest: request => {
            sent.push(request as unknown as { diff: string })
            if (options.capped) {
              return Promise.reject(
                new AssistCapReachedError(
                  'the AI credits of 2026-11 are used: 4 of a cap of 4. Nothing was sent to the model: an administrator may raise the cap',
                  402
                )
              )
            }
            return fake.suggest(request)
          },
        }
      },
    }).connect(serverSide)
    const agent = new Client({ name: 'test', version: '0.0.0' })
    await agent.connect(clientSide)
    const call = async (args: Record<string, unknown>) => {
      const result = (await agent.callTool({
        name: 'propose_decision',
        arguments: args,
      })) as { content: { text: string }[]; isError?: boolean }
      const text = result.content[0]!.text
      return result.isError
        ? { error: text }
        : (JSON.parse(text) as Record<string, unknown>)
    }
    return {
      call,
      sent,
      close: async () => {
        await agent.close()
        repo.remove()
      },
    }
  }

  it('returns the record that the service drafts from the change', async () => {
    const server = await serve({ optIn: true })
    const diff = `${change('src/db/pool.ts')}\n${change('config/secrets/keys.ts')}`
    const answer = await server.call({ assist: true, diff })
    expect(answer).toMatchObject({
      path: 'docs/adr/0002-pool-size.md',
      number: 2,
      assist: {
        model: 'fake',
        // The guard reads the path between backticks.
        problems: [],
        excluded: ['config/secrets/keys.ts'],
      },
    })
    const content = answer.content as string
    expect(content).toContain('# 2. Pool size')
    expect(content).toContain('Amends ADR 0001.')
    expect(content).toContain('### Twenty connections')
    expect(content).toContain(
      '  rule: The pool keeps twenty connections at most.'
    )
    // The files that compadr.yml keeps never leave.
    expect(server.sent).toHaveLength(1)
    expect(server.sent[0]!.diff).toContain('src/db/pool.ts')
    expect(server.sent[0]!.diff).not.toContain('config/secrets')
    await server.close()
  })

  it('gives notNeeded and no record when the change only applies a decision', async () => {
    const server = await serve({
      optIn: true,
      notNeeded: 'The change only applies ADR 0001.',
    })
    const answer = await server.call({
      assist: true,
      diff: change('src/db/pool.ts'),
    })
    expect(answer).toMatchObject({
      notNeeded: 'The change only applies ADR 0001.',
    })
    expect(answer).not.toHaveProperty('content')
    await server.close()
  })

  it('says that no record was drafted at the cap of the AI credits', async () => {
    const server = await serve({ optIn: true, capped: true })
    const answer = await server.call({
      assist: true,
      diff: change('src/db/pool.ts'),
    })
    expect(answer.error as string).toContain(
      'No record was drafted: the AI credits of 2026-11 are used: 4 of a cap of 4'
    )
    await server.close()
  })

  it('sends nothing without the consent of compadr.yml, nor for a bad call', async () => {
    const error = async (
      server: Awaited<ReturnType<typeof serve>>,
      args: Record<string, unknown>
    ) => (await server.call(args)).error as string
    const off = await serve({ optIn: false })
    expect(
      await error(off, { assist: true, diff: change('src/db/pool.ts') })
    ).toContain(
      'No record was drafted: the assist service is off for this repository'
    )
    expect(off.sent).toEqual([])
    await off.close()

    const on = await serve({ optIn: true })
    expect(await error(on, { assist: true })).toContain(
      'pass the diff of the change'
    )
    expect(
      await error(on, {
        assist: true,
        diff: change('src/db/pool.ts'),
        title: 'Mine',
      })
    ).toContain('the service writes title')
    expect(
      await error(on, { assist: true, diff: change('config/secrets/keys.ts') })
    ).toContain('every file of the change')
    expect(await error(on, { diff: change('src/db/pool.ts') })).toContain(
      'The diff goes with "assist": true'
    )
    expect(await error(on, {})).toContain('Pass the title of the decision')
    expect(on.sent).toEqual([])
    await on.close()
  })
})
