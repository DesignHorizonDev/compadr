import type { Decision, DriftReport } from '@compadr/format'
import { describe, expect, it } from 'vitest'
import {
  AgentsExcerptError,
  findAgentsExcerpt,
  recordLanguage,
  renderAgentsExcerpt,
  renderIndex,
  renderMemoryCard,
  writeAgentsExcerpt,
} from './generated.ts'
import { generatedFileProblems } from './check.ts'

function decision(
  number: number,
  title: string,
  status: Decision['status'] = 'accepted'
): Decision {
  return {
    number,
    file: `docs/adr/${String(number).padStart(4, '0')}-x.md`,
    title,
    status,
    rawStatus: status,
    date: null,
    revisedAt: null,
    lineCount: 10,
    feature: null,
    parent: null,
    amends: [],
    amendedBy: [],
    supersededBy: [],
    codeArea: null,
  }
}

function report(
  decisions: Decision[],
  features: DriftReport['features'] = []
): DriftReport {
  return {
    schemaVersion: 2,
    generator: { name: 'compadr', version: '0.0.0' },
    repository: { name: 'r', ref: 'HEAD', commit: 'c', adrDir: 'docs/adr' },
    generatedAt: '2026-11-03T10:00:00Z',
    decisions,
    references: [],
    citations: [],
    signals: [],
    families: [],
    features,
  }
}

const billing = report(
  [
    decision(1, 'Monthly invoices'),
    decision(2, 'Daily invoices'),
    decision(3, 'Paper invoices', 'superseded'),
    decision(4, 'Refund window', 'proposed'),
    decision(5, 'Logging'),
    decision(6, 'Old logging', 'rejected'),
  ],
  [
    {
      id: 'billing',
      label: 'Billing',
      main: 2,
      source: 'declared',
      decisions: [1, 2, 3, 4],
    },
  ]
)

describe('recordLanguage', () => {
  it('reads French when most titles are French', () => {
    expect(recordLanguage(billing)).toBe('en')
    expect(
      recordLanguage(
        report([
          decision(1, 'Adresse de réponse des mails'),
          decision(2, 'Module classement'),
          decision(3, 'Export pour un admin'),
        ])
      )
    ).toBe('fr')
  })
})

describe('renderIndex', () => {
  it('lists the decisions in force by feature, the main one first', () => {
    expect(renderIndex(billing)).toBe(
      [
        '<!-- Generated by Compadr: compadr index -->',
        '',
        '# Decisions in force',
        '',
        'This file lists the decisions in force, by feature. Compadr generates it from the records of `docs/adr`: run `compadr index` again instead of editing it.',
        '',
        '## Billing',
        '',
        '- [0002](0002-x.md) Daily invoices (main decision)',
        '- [0001](0001-x.md) Monthly invoices',
        '- [0004](0004-x.md) Refund window (proposed)',
        '',
        '## Not in a feature',
        '',
        '- [0005](0005-x.md) Logging',
        '',
      ].join('\n')
    )
  })

  it('gives one list without section when no feature is declared', () => {
    const index = renderIndex(report([decision(1, 'A'), decision(2, 'B')]))
    expect(index).not.toContain('##')
    expect(index).toContain('- [0001](0001-x.md) A\n- [0002](0002-x.md) B\n')
  })
})

describe('the excerpt for agents', () => {
  const excerpt = renderAgentsExcerpt(billing)

  it('names the features and their main decision between markers', () => {
    expect(
      excerpt.startsWith('<!-- compadr:start -->\n## Architecture decisions\n')
    ).toBe(true)
    expect(excerpt).toContain('- Billing: 0002 Daily invoices\n')
    expect(excerpt.endsWith('<!-- compadr:end -->\n')).toBe(true)
  })

  it('creates, appends and replaces the excerpt', () => {
    expect(writeAgentsExcerpt(null, excerpt)).toBe(excerpt)
    const appended = writeAgentsExcerpt('# Agents\n\nBe kind.', excerpt)
    expect(appended).toBe(`# Agents\n\nBe kind.\n\n${excerpt}`)
    const old = '<!-- compadr:start -->\nold\n<!-- compadr:end -->\n'
    const replaced = writeAgentsExcerpt(`# Agents\n\n${old}\nAfter.\n`, excerpt)
    expect(replaced).toBe(`# Agents\n\n${excerpt}\nAfter.\n`)
    expect(findAgentsExcerpt(replaced)).toBe(excerpt)
  })

  it('refuses a start marker without its end', () => {
    expect(() =>
      writeAgentsExcerpt('<!-- compadr:start -->\nMy notes.\n', excerpt)
    ).toThrow(AgentsExcerptError)
  })
})

describe('renderMemoryCard', () => {
  const zone = (
    path: string,
    linkedFiles: number,
    decisions: number[],
    coverage: 'strong' | 'partial' | 'none' = 'strong'
  ) => ({
    path,
    own: false,
    files: 10,
    linkedFiles,
    crossChecked: 1,
    weight: 4,
    decisions: decisions.map(number => ({ number, weight: 10 - number })),
    folderCited: [],
    coverage,
  })
  const card = {
    ...billing,
    decisions: billing.decisions.map(d =>
      d.number === 2
        ? {
            ...d,
            rule: {
              text: 'Invoices leave every day at midnight from the billing queue, and the worker stores each run with the option `retry: "daily"` set.',
              source: 'declared' as const,
            },
          }
        : d
    ),
    zones: [
      zone('server/billing', 5, [5, 2, 1, 9, 8, 7, 6, 11, 12, 10]),
      zone('server/mail', 2, [5]),
      zone('web', 0, [], 'none'),
    ],
  }

  it('gives the features, the zones with three linked files or more, and the other decisions', () => {
    expect(renderMemoryCard(card)).toBe(
      [
        '<!-- Generated by Compadr: compadr map -->',
        '',
        '# Memory of the decisions',
        '',
        '3 decisions are in force in `docs/adr`. Compadr generates this file from the records and the code: run `compadr map` again instead of editing it.',
        '',
        'Before you change a file of a zone marked strong or partial, call `decisions_for_file`. Open a record with `get_decision` only when `read` says `lines` or `record`, by its outline first.',
        '',
        '## Features',
        '',
        // The rule stops on a word, before the code span it would cut.
        '- Billing: 0002 Daily invoices. Rule: Invoices leave every day at midnight from the billing queue, and the worker stores each run with the option… (details: 0001)',
        '',
        '## Zones of the code',
        '',
        '| Zone | Coverage | Decisions |',
        '|---|---|---|',
        // By number, not by weight: the card changes less with the code.
        '| `server/billing` | strong | 0001 0002 0005 0006 0007 0008 0009 0010 +2 |',
        '',
        '## Other decisions in force',
        '',
        '- 0005 Logging',
        '',
      ].join('\n')
    )
  })

  it('marks a proposed main decision and gives no rule for it', () => {
    const proposed = {
      ...card,
      decisions: card.decisions.map(d =>
        d.number === 2 ? { ...d, status: 'proposed' as const } : d
      ),
    }
    expect(renderMemoryCard(proposed)).toContain(
      '- Billing: 0002 Daily invoices (proposed). (details: 0001)'
    )
  })

  it('writes in French for French records', () => {
    const french = {
      ...card,
      decisions: card.decisions.map(d => ({
        ...d,
        title: `Décision ${d.number} de la facture`,
      })),
    }
    const text = renderMemoryCard(french)
    expect(text).toContain('# Mémoire des décisions')
    expect(text).toContain('- Billing : 0002 Décision 2 de la facture. Règle :')
  })

  it('makes check name a card that no longer matches', () => {
    const file = 'docs/adr/MAP.md'
    expect(
      generatedFileProblems(card, new Map([[file, renderMemoryCard(card)]]))
    ).toEqual([])
    const stale = renderMemoryCard({ ...card, zones: [] })
    expect(
      generatedFileProblems(card, new Map([[file, stale]])).map(p => [
        p.rule,
        p.file,
        p.message,
      ])
    ).toEqual([
      [
        'generated-file-stale',
        file,
        'docs/adr/MAP.md no longer matches the decision records: run compadr map',
      ],
    ])
  })
})
