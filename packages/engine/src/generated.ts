/** A decision that the index lists: in force, and not rejected. */
function listed(decision: Decision): boolean {
  return isInForce(decision.status) && decision.status !== 'rejected'
}

/** The groups of the index: each declared feature, then the others. */
function groups(
  report: DriftReport
): { label: string; main: number | null; decisions: Decision[] }[] {
  const byNumber = new Map(report.decisions.map(d => [d.number, d]))
  const declared = (report.features ?? []).filter(f => f.source === 'declared')
  const grouped = new Set<number>()
  const result = declared.map(feature => {
    const members = feature.decisions
      .map(n => byNumber.get(n))
      .filter((d): d is Decision => d !== undefined)
    for (const d of members) grouped.add(d.number)
    // The main decision first, then the details in their order.
    const decisions = members
      .filter(listed)
      .sort(
        (a, b) =>
          Number(b.number === feature.main) -
            Number(a.number === feature.main) || a.number - b.number
      )
    return { label: feature.label, main: feature.main, decisions }
  })
  const rest = report.decisions.filter(d => !grouped.has(d.number) && listed(d))
  if (rest.length > 0) {
    result.push({ label: '', main: null, decisions: rest })
  }
  return result.filter(group => group.decisions.length > 0)
}

/** Content of `INDEX.md` in the ADR folder. */
export function renderIndex(report: DriftReport): string {
  const words = WORDS[recordLanguage(report)]
  const adrDir = report.repository.adrDir
  const lines = [INDEX_MARKER, '', `# ${words.title}`, '', words.intro(adrDir)]
  const all = groups(report)
  const titled = all.some(group => group.label !== '')
  for (const group of all) {
    lines.push('')
    if (titled) {
      lines.push(`## ${group.label === '' ? words.outside : group.label}`, '')
    }
    for (const d of group.decisions) {
      const notes = [
        ...(d.number === group.main ? [words.main] : []),
        ...(d.status === 'proposed' ? [words.proposed] : []),
      ]
      const link = posix.relative(adrDir, d.file)
      lines.push(
        `- [${pad(d.number)}](${link}) ${d.title}${notes.length > 0 ? ` (${notes.join(', ')})` : ''}`
      )
    }
  }
  if (all.length === 0) lines.push('', words.none)
  return `${lines.join('\n')}\n`
}

/**
 * Content of `MAP.md` in the ADR folder: the memory card that a coding agent
 * reads once per session. It gives the features with the rule of their main
 * decision, the zones of the code that three linked files or more put under
 * decisions, and the titles of the other decisions in force. It leaves out
 * dates, signals and weights, so that it changes with the records and the
 * links, not with each commit.
 */
export function renderMemoryCard(report: DriftReport): string {
  const words = WORDS[recordLanguage(report)]
  const adrDir = report.repository.adrDir
  const inForce = report.decisions.filter(d => d.status === 'accepted')
  const lines = [
    MAP_MARKER,
    '',
    `# ${words.mapTitle}`,
    '',
    ...words.mapIntro(inForce.length, adrDir),
  ]
  const all = groups(report)
  const features = all.filter(group => group.label !== '')
  if (features.length > 0) {
    lines.push('', `## ${words.mapFeatures}`, '')
    for (const feature of features) {
      const main = feature.decisions.find(d => d.number === feature.main)
      const details = feature.decisions
        .filter(d => d !== main && d.status === 'accepted')
        .map(d => pad(d.number))
      // A proposed main decision binds nothing yet: no rule, and it says so.
      const proposed = main !== undefined && main.status !== 'accepted'
      const parts = [
        main === undefined
          ? `- ${feature.label}`
          : `- ${feature.label}${words.colon} ${pad(main.number)} ${main.title}${proposed ? ` (${words.proposed})` : ''}.`,
        ...(main?.rule && !proposed
          ? [
              `${words.mapRule}${words.colon} ${shorten(main.rule.text, MAP_RULE_LENGTH)}`,
            ]
          : []),
        ...(details.length > 0
          ? [`(${words.mapDetails}${words.colon} ${details.join(', ')})`]
          : []),
      ]
      lines.push(parts.join(' '))
    }
  }
  const zones = (report.zones ?? []).filter(
    zone => zone.linkedFiles >= MAP_MIN_LINKED_FILES
  )
  lines.push('', `## ${words.mapZones}`, '')
  if (zones.length === 0) {
    lines.push(words.mapNoZone)
  } else {
    lines.push(words.mapZoneHead, '|---|---|---|')
    for (const zone of zones) {
      const numbers = zone.decisions.map(d => d.number).sort((a, b) => a - b)
      const shown = numbers.slice(0, MAP_ZONE_DECISIONS).map(pad)
      const more = numbers.length - shown.length
      const path = zone.own ? `${zone.path} (${words.mapOwn})` : zone.path
      lines.push(
        `| \`${path}\` | ${zone.coverage} | ${shown.join(' ')}${more > 0 ? ` +${more}` : ''} |`
      )
    }
  }
  const others = all
    .filter(group => group.label === '')
    .flatMap(group => group.decisions)
    .filter(d => d.status === 'accepted')
  if (others.length > 0) {
    lines.push(
      '',
      `## ${features.length > 0 ? words.mapOthers : words.mapAll}`,
      ''
    )
    for (const d of others) lines.push(`- ${pad(d.number)} ${d.title}`)
  }
  return `${lines.join('\n')}\n`
}

/** The excerpt for AGENTS.md or CLAUDE.md, markers included. */
export function renderAgentsExcerpt(report: DriftReport): string {
  const words = WORDS[recordLanguage(report)]
  const byNumber = new Map(report.decisions.map(d => [d.number, d]))
  const lines = [
    AGENTS_START,
    `## ${words.agentsTitle}`,
    '',
    ...words.agents(report.repository.adrDir),
  ]
  const features = groups(report).filter(g => g.label !== '')
  if (features.length > 0) {
    lines.push('', words.features, '')
    for (const feature of features) {
      const main =
        feature.main === null ? undefined : byNumber.get(feature.main)
      lines.push(
        main === undefined
          ? `- ${feature.label}`
          : `- ${feature.label}: ${pad(main.number)} ${main.title}`
      )
    }
  }
  lines.push(AGENTS_END)
  return `${lines.join('\n')}\n`
}

/** A file whose excerpt has a start marker without an end marker. */
export class AgentsExcerptError extends Error {}

/** The excerpt of `content`, markers included, or null when it has none. */
export function findAgentsExcerpt(content: string): string | null {
  const start = content.indexOf(AGENTS_START)
  if (start === -1) return null
  const end = content.indexOf(AGENTS_END, start)
  if (end === -1) return null
  const after = content.indexOf('\n', end)
  return content.slice(start, after === -1 ? undefined : after + 1)
}

/**
 * `content` with its excerpt replaced by `excerpt`. A file without excerpt
 * receives it at the end; a missing file is created.
 */
export function writeAgentsExcerpt(
  content: string | null,
  excerpt: string
): string {
  if (content === null || content === '') return excerpt
  const current = findAgentsExcerpt(content)
  if (current !== null) return content.replace(current, () => excerpt)
  // Appending would leave the start marker in place, and a later run would
  // replace the text between it and the new end marker.
  if (content.includes(AGENTS_START)) {
    throw new AgentsExcerptError(
      `the file has ${AGENTS_START} without ${AGENTS_END}: remove the marker or add its end`
    )
  }
  const separator = content.endsWith('\n\n')
    ? ''
    : content.endsWith('\n')
      ? '\n'
      : '\n\n'
  return `${content}${separator}${excerpt}`
}
