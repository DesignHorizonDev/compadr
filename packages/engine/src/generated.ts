// Files that Compadr generates from the decision records: the index of the
// decisions in force, the memory card for coding agents, and the excerpt for
// their instructions. Each depends on the report only, so `compadr check` can
// tell whether a committed copy is still up to date.
import { posix } from 'node:path'
import { isInForce, type Decision, type DriftReport } from '@compadr/format'

export type RecordLanguage = 'en' | 'fr'

/** Name of the index in the ADR folder. */
export const INDEX_FILE = 'INDEX.md'

/** First line of a generated index: `check` compares only such a file. */
export const INDEX_MARKER = '<!-- Generated by Compadr: compadr index -->'

/** Name of the memory card in the ADR folder. */
export const MAP_FILE = 'MAP.md'

/** First line of a generated memory card. */
export const MAP_MARKER = '<!-- Generated by Compadr: compadr map -->'

/** A zone enters the memory card from this number of linked files. */
export const MAP_MIN_LINKED_FILES = 3

/** Decisions named on the line of a zone; the others are counted. */
export const MAP_ZONE_DECISIONS = 8

/** Longest rule in the memory card, in characters. */
export const MAP_RULE_LENGTH = 120

/**
 * `text` cut on a word to `length` characters at most. A cut inside a code
 * span drops the span, so that no backtick stays open.
 */
function shorten(text: string, length: number): string {
  if (text.length <= length) return text
  let cut = text.slice(0, length - 1)
  const space = cut.lastIndexOf(' ')
  if (space > length / 2) cut = cut.slice(0, space)
  if ((cut.match(/`/g) ?? []).length % 2 === 1) {
    cut = cut.slice(0, cut.lastIndexOf('`'))
  }
  return `${cut
    .trimEnd()
    .replace(/[,;:(]$/, '')
    .trimEnd()}…`
}

/** The lines that frame the excerpt in AGENTS.md or CLAUDE.md. */
export const AGENTS_START = '<!-- compadr:start -->'
export const AGENTS_END = '<!-- compadr:end -->'

/** Files where `check` looks for the excerpt. */
export const AGENTS_FILES = ['AGENTS.md', 'CLAUDE.md'] as const

const pad = (n: number) => String(n).padStart(4, '0')

// A French title has an accented letter or a common French word.
const FRENCH =
  /[àâçéèêëîïôûùü]|\b(?:le|la|les|des|du|de|et|une?|pour|par|sur|dans|aux?|avec|sans)\b/i

/**
 * Language of the records: French when most titles read as French. Compadr
 * writes the generated files in that language.
 */
export function recordLanguage(report: DriftReport): RecordLanguage {
  const french = report.decisions.filter(d => FRENCH.test(d.title)).length
  return french * 2 > report.decisions.length ? 'fr' : 'en'
}

