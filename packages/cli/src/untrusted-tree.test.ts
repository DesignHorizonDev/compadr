import {
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { createFixtureRepo, type FixtureRepo } from '@compadr/engine/testing'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { main } from './main.ts'
import {
  checkCorrectionPath,
  commitFiles,
  PublishError,
  runCommand,
} from './publish.ts'

// The tree of an analysed commit comes from whoever wrote it. A link of that
// tree must not lead a correction to write outside its clone.
let fixture: FixtureRepo
let outside: string
let cacheDir: string

beforeAll(() => {
  fixture = createFixtureRepo([
    {
      date: '2026-01-10T09:00:00Z',
      files: {
        'docs/adr/0001-pool.md':
          '# ADR 0001 — Pool\n\n- **Status:** Accepted\n\nSee `src/pool.ts`.\n',
        'src/pool.ts': 'one\n',
      },
    },
  ])
  outside = mkdtempSync(join(tmpdir(), 'compadr-outside-'))
  writeFileSync(join(outside, 'target'), 'kept\n')
  // A link to an existing file, and a link that leads nowhere yet.
  symlinkSync(join(outside, 'target'), join(fixture.path, 'docs/adr/INDEX.md'))
  symlinkSync(join(outside, 'created'), join(fixture.path, 'docs/adr/MAP.md'))
  fixture.git('add', '--', 'docs')
  fixture.git(
    '-c',
    'user.name=Compadr',
    '-c',
    'user.email=fixture@example.com',
    'commit',
    '-q',
    '-m',
    'Add the links'
  )
  fixture.git('config', 'user.name', 'Draft Author')
  fixture.git('config', 'user.email', 'draft@example.com')
  cacheDir = mkdtempSync(join(tmpdir(), 'compadr-cache-'))
})

afterAll(() => {
  fixture.remove()
  rmSync(outside, { recursive: true, force: true })
  rmSync(cacheDir, { recursive: true, force: true })
})

async function run(argv: string[]) {
  const out: string[] = []
  const err: string[] = []
  const code = await main(argv, {
    out: line => out.push(line),
    err: line => err.push(line),
  })
  return { code, out: out.join('\n'), err: err.join('\n') }
}

function expectNothingOutside() {
  expect(readFileSync(join(outside, 'target'), 'utf8')).toBe('kept\n')
  expect(() => readFileSync(join(outside, 'created'))).toThrow()
}

describe('a correction on a tree that holds links', () => {
  it('replaces the link in the commit and writes nothing outside', async () => {
    for (const command of ['index', 'map']) {
      const result = await run([command, fixture.path])
      expect(result.code).toBe(0)
      // The commit turns the link into a file.
      expect(result.out).toContain('deleted file mode 120000')
      expect(result.out).toContain('new file mode 100644')
      expect(result.out).toContain('Generated by Compadr')
    }
    expectNothingOutside()
  })

  it('does the same on a draft', async () => {
    for (const command of ['index', 'map']) {
      const result = await run([
        command,
        fixture.path,
        '--draft',
        'links',
        '--cache-dir',
        cacheDir,
      ])
      expect(result.code).toBe(0)
    }
    expectNothingOutside()
  })
})

describe('commitFiles', () => {
  let tree: FixtureRepo
  let parent: string

  beforeAll(() => {
    tree = createFixtureRepo([
      {
        date: '2026-01-10T09:00:00Z',
        files: { 'tools/run.sh': '#!/bin/sh\n', 'real/a.md': 'a\n' },
      },
    ])
    tree.git('update-index', '--chmod=+x', 'tools/run.sh')
    // A folder versioned as a link.
    symlinkSync('real', join(tree.path, 'linked'))
    tree.git('add', '--', 'linked')
    tree.git(
      '-c',
      'user.name=Compadr',
      '-c',
      'user.email=fixture@example.com',
      'commit',
      '-q',
      '-m',
      'Add an executable and a linked folder'
    )
    parent = tree.git('rev-parse', 'HEAD').trim()
  })

  afterAll(() => tree.remove())

  const commit = (files: Record<string, string>) =>
    commitFiles(runCommand, tree.path, {
      parent,
      files: new Map(Object.entries(files)),
      identity: [
        '-c',
        'user.name=Compadr',
        '-c',
        'user.email=fixture@example.com',
      ],
      title: 'Correction',
      body: 'Body',
    })

  it('keeps an executable file executable', async () => {
    const created = await commit({ 'tools/run.sh': '#!/bin/sh\necho\n' })
    expect(tree.git('ls-tree', created, '--', 'tools/run.sh')).toMatch(
      /^100755 /
    )
  })

  it('writes several files in one commit', async () => {
    const created = await commit({ 'one.md': '1\n', 'real/two.md': '2\n' })
    expect(tree.git('show', `${created}:one.md`)).toBe('1\n')
    expect(tree.git('show', `${created}:real/two.md`)).toBe('2\n')
  })

  it('refuses a path under a folder versioned as a link', async () => {
    await expect(commit({ 'linked/INDEX.md': 'x\n' })).rejects.toThrow(
      new PublishError(
        'linked/INDEX.md cannot be written: linked is not a folder in the repository'
      )
    )
    await expect(commit({ real: 'x\n' })).rejects.toThrow(PublishError)
  })
})

describe('checkCorrectionPath', () => {
  it('accepts a path inside the repository', () => {
    expect(checkCorrectionPath('docs/adr/INDEX.md')).toBe('docs/adr/INDEX.md')
  })

  it('refuses a path that leaves the repository or names .git', () => {
    for (const path of [
      '../x',
      'docs/../../x',
      '/etc/x',
      './x',
      'docs//x',
      '.git/config',
      'docs/.GIT/hooks/pre-commit',
      'x\0y',
      '',
    ]) {
      expect(() => checkCorrectionPath(path)).toThrow(PublishError)
    }
  })
})
